// Regenerates lib/drivers/panasonic-data.js from the Bitfocus Companion module
// bitfocus/companion-module-panasonic-ptz (MIT, Copyright (c) 2018 Bitfocus AS), src/models.js + src/choices.js.
// Usage: node tools/gen-panasonic-data.mjs <path-to-companion-module-panasonic-ptz>
import fs from 'fs'
import path from 'path'
import { execSync } from 'child_process'
const dir = path.resolve(process.argv[2] || '../ptz/companion-module-panasonic-ptz')
const { MODELS, SERIES_SPECS } = await import(path.join(dir, 'src/models.js'))
const { c } = await import(path.join(dir, 'src/choices.js'))
const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
let commit = ''
try { commit = execSync('git rev-parse --short HEAD', { cwd: dir }).toString().trim() } catch {}
// choice tables are shared between series; store each once
const tables = {}
const tableId = (arr) => {
  for (let i = 0; i < 3 && typeof arr === "function"; i++) arr = arr.call(c)
  if (!Array.isArray(arr)) { console.warn("unresolvable dropdown (module bug), left empty"); arr = [] }
  const rows = arr.map((x) => [String(x.id), String(x.label)])
  const key = JSON.stringify(rows)
  for (const [k, v] of Object.entries(tables)) if (JSON.stringify(v) === key) return k
  const k = `T${Object.keys(tables).length}`; tables[k] = rows; return k
}
const series = {}
for (const s of SERIES_SPECS) {
  const caps = {}; const lists = {}
  for (const [k, v] of Object.entries(s.actions)) {
    if (!v) continue
    caps[k] = true
    if (v && typeof v === 'object' && v.cmd) lists[k] = { cmd: v.cmd, table: v.dropdown ? tableId(v.dropdown) : null }
  }
  series[s.id] = { caps, lists, feedbacks: Object.keys(s.feedbacks).filter((k) => s.feedbacks[k]), variables: Object.keys(s.variables).filter((k) => s.variables[k]) }
}
const out = {
  source: { repo: 'https://github.com/bitfocus/companion-module-panasonic-ptz', version: pkg.version, commit, license: 'MIT, Copyright (c) 2018 Bitfocus AS' },
  models: MODELS.map((m) => [m.id, m.series, m.label]),
  series,
  tables,
  presetSpeeds: c.CHOICES_PSSPEED.map((x) => [String(x.id), x.label]),
  presetTimes: c.CHOICES_PSTIME().map((x) => [String(x.id), x.label]),
}
const js = `'use strict';
// GENERATED by tools/gen-panasonic-data.mjs - do not edit by hand.
// Model -> series table, per-series capabilities and value lists from the Bitfocus Companion module
// ${out.source.repo} v${out.source.version}${commit ? ` (commit ${commit})` : ''}, src/models.js and src/choices.js.
// ${out.source.license}. Permission is hereby granted, free of charge, to any person obtaining a copy of this
// software ... (full MIT text: https://github.com/bitfocus/companion-module-panasonic-ptz/blob/main/LICENSE).
module.exports = ${JSON.stringify(out)};
`
fs.writeFileSync(new URL('../lib/drivers/panasonic-data.js', import.meta.url), js)
console.log('wrote panasonic-data.js', js.length, 'bytes,', Object.keys(tables).length, 'tables,', MODELS.length, 'models')
