// Prints the PTZ command reference (markdown) from lib/drivers/ptz-commands.js: every command, its source and
// which model series offer it. Usage: node tools/ptz-command-table.js > docs/ptz-commands.md
'use strict';
const P = require('../lib/drivers/ptz-commands');
const series = Object.keys(P.DATA.series);
const S = ['UE150', 'AW-HE130', 'AW-HE120', 'AW-HR140', 'HE40', 'HE42', 'UE70', 'AW-UE4', 'AW-HE2', 'CX350', 'AK-UB300', 'Other'].filter((x) => series.includes(x));
const avail = (id, s) => P.catalogFor(s).ops.some((o) => o.id === id);
const row = (o) => `| \`${o.id}\` | ${o.label} | ${o.src === 'spec' ? 'spec' : o.src === 'app' ? 'app' : 'module'} | ${String(o.ref).replace(/\|/g, '/')} | ${S.map((s) => (avail(o.id, s) ? '●' : '')).join(' | ')} |`;
const out = [
  '# Panasonic PTZ command reference (generated)',
  '',
  `Generated by \`node tools/ptz-command-table.js\` from \`lib/drivers/ptz-commands.js\`. Sources: **module** = Bitfocus Companion module`,
  `${P.DATA.source.repo} v${P.DATA.source.version} (${P.DATA.source.commit}), **spec** = Panasonic AW-UE150 / AW-HE145 Interface Specifications v2.94`,
  '(+ Supplement for Web Control). Spec commands are offered on the UE150 series only (AW-UE100 / UE150 / UE155 / HE145 / UN145 in the',
  'module\'s model table); other models may support some of them; confirm on hardware first.',
  '',
  `| id | command | source | reference | ${S.join(' | ')} |`,
  `|---|---|---|---|${S.map(() => ':-:').join('|')}|`,
  ...P.MOTION.map(row),
  ...P.COMMANDS.map(row),
  '',
  '## Companion module action -> app command',
  '',
  '| module action | app command |', '|---|---|',
  ...Object.entries(P.MODULE_ACTIONS).map(([a, b]) => `| ${a} | \`${b}\` |`),
  '',
];
process.stdout.write(out.join('\n'));
